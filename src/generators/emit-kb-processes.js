// Readable pages for the standard process knowledge base, generated from kb/capabilities/processes.json (what the
// Fit-gap sub-agent reads) so the pages and the matching never drift apart. Each step lists its standard objects and
// the official sources behind it, with the words quoted from them (kb/capabilities/sources.json).
//
//   node src/generators/emit-kb-processes.js
const fs = require('fs');
const path = require('path');
const P = require('../paths');

const DIR = path.join(P.ROOT, 'kb', 'capabilities');
const kb = JSON.parse(fs.readFileSync(path.join(DIR, 'processes.json'), 'utf8'));
const sources = JSON.parse(fs.readFileSync(path.join(DIR, 'sources.json'), 'utf8')).sources;
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
const byId = Object.fromEntries(sources.map((s) => [s.id, s]));
const missing = kb.areas.flatMap((a) => a.capabilities.flatMap((c) => c.steps.flatMap((s) => (s.sources || []).filter((id) => !byId[id]).map((id) => `${s.id}: ${id}`))));
if (missing.length) { console.error(`kb processes: unknown sources ${missing.join(', ')}`); process.exit(1); }
const host = (u) => { try { const x = new URL(u); return x.hostname.replace(/^www\./, '').replace(/^resources\.docs\./, '') + (x.pathname.endsWith('.pdf') ? ' (PDF)' : ''); } catch { return u; } };

const HEAD = (title, intro) => [`# ${title}`, '', 'Owner: Engineering standards · used by the Discovery agent (Fit-gap sub-agent) and by reviewers at the Discover gate.',
  'Generated by `src/generators/emit-kb-processes.js` from [processes.json](processes.json). Do not edit; edit the JSON and its sources.', '', intro, ''];

function page(areas) {
  const out = [];
  for (const a of areas) {
    out.push(`## ${a.area}`, '');
    for (const c of a.capabilities) {
      out.push(`### ${c.name}`, '', c.standard, '', '| Step | Standard objects and features | Official source |', '|---|---|---|');
      for (const s of c.steps) {
        const src = (s.sources || []).map((id) => `[${host(byId[id].url)}](${byId[id].url}): "${esc(byId[id].quote)}"`).join('<br>');
        out.push(`| ${esc(s.name)} | ${(s.objects || []).map((o) => `\`${o}\``).join(', ') || esc(s.standard)} | ${src} |`);
      }
      out.push('');
    }
  }
  return out;
}

const groups = {};
for (const a of kb.areas) (groups[a.guide] ||= []).push(a);
const TITLES = {
  'consumer-goods-processes.md': ['Consumer Goods standard processes', 'Retail Execution and Trade Promotion Management in Consumer Goods Cloud (now named Agentforce Consumer Goods): the capabilities, their process steps in business order, and the standard objects of each step.'],
  'core-processes.md': ['Core Salesforce standard processes', 'Customer master, product master, order to cash, sales performance and service on standard Salesforce: the capabilities, their process steps in business order, and the standard objects of each step.'],
};
for (const [file, areas] of Object.entries(groups)) {
  const [title, intro] = TITLES[file] || [file, ''];
  fs.writeFileSync(path.join(DIR, file), `${[...HEAD(title, intro), ...page(areas)].join('\n').replace(/\n{3,}/g, '\n\n')}\n`);
}
const steps = kb.areas.reduce((n, a) => n + a.capabilities.reduce((m, c) => m + c.steps.length, 0), 0);
console.log(`kb processes: ${kb.areas.length} areas, ${kb.areas.reduce((n, a) => n + a.capabilities.length, 0)} capabilities, ${steps} steps -> ${Object.keys(groups).map((f) => `kb/capabilities/${f}`).join(', ')}`);
