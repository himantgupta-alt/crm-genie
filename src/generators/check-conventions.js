// Conventions check, run in CI. Fails (exit 1) with a list of violations.
//
//   node src/generators/check-conventions.js
//
// 1. All JavaScript in src/ parses.
// 2. No code refers to the pre-ADLC layout (sf-extract/, target/db, output/...).
// 3. Every migration lives in its owning agent's folder, numbers are unique, and it carries the Owner and GENERATED headers.
// 4. Every Markdown output under adlc/ names its owner in its first lines.
// 5. Every agent spec has an outputDir that exists, and every concrete output it declares exists.
// 6. Every agent output folder has a README (the ADLC index).
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const P = require('../paths');

const problems = [];
const walk = (dir, keep, skip = /node_modules|[\\/]runs[\\/]|force-app/) => (fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  if (skip.test(p)) return [];
  return e.isDirectory() ? walk(p, keep, skip) : keep(p) ? [p] : [];
}) : []);

// 1 + 2
for (const f of walk(P.SRC, (p) => /\.(js|mjs)$/.test(p))) {
  try { execFileSync(process.execPath, ['--check', f], { stdio: 'pipe' }); } catch (e) { problems.push(`syntax: ${P.rel(f)}: ${String(e.stderr).split('\n')[4] || 'does not parse'}`); }
  const t = fs.readFileSync(f, 'utf8');
  if (path.basename(f) !== 'check-conventions.js' && /sf-extract\/|['"]target['"],\s*['"]db['"]|['"]output['"],/.test(t)) problems.push(`legacy path: ${P.rel(f)} still refers to the pre-ADLC layout`);
}

// 3
const seen = new Map();
for (const f of P.sqlFiles()) {
  const name = path.basename(f), n = name.slice(0, 3);
  if (seen.has(n)) problems.push(`migration: number ${n} used twice (${seen.get(n)}, ${P.rel(f)})`);
  seen.set(n, P.rel(f));
  if (path.dirname(f) !== P.sqlDirFor(name)) problems.push(`migration: ${P.rel(f)} is not in its owning agent's folder (${P.rel(P.sqlDirFor(name))})`);
  const head = fs.readFileSync(f, 'utf8').split('\n').slice(0, 4).join('\n');
  if (!/^-- Owner: /m.test(head) || !/-- GENERATED by /.test(head)) problems.push(`provenance: ${P.rel(f)} lacks the Owner/GENERATED header`);
}

// 4
for (const f of walk(P.ADLC, (p) => p.endsWith('.md') && !/[\\/](report|load-report)\.md$/.test(p))) {
  const head = fs.readFileSync(f, 'utf8').split('\n').slice(0, 6).join('\n');
  if (!/Owner:|Generated by/.test(head)) problems.push(`provenance: ${P.rel(f)} does not name its owner in its first lines`);
}

// 5 + 6
for (const d of fs.readdirSync(P.AGENTS, { withFileTypes: true }).filter((x) => x.isDirectory())) {
  const sf = path.join(P.AGENTS, d.name, 'agent.json');
  if (!fs.existsSync(sf)) continue;
  const s = JSON.parse(fs.readFileSync(sf, 'utf8'));
  if (!s.outputDir) { problems.push(`spec: ${d.name} has no outputDir`); continue; }
  const dir = path.join(P.ROOT, s.outputDir);
  if (!fs.existsSync(dir)) problems.push(`spec: ${d.name} outputDir ${s.outputDir} does not exist`);
  if (!fs.existsSync(path.join(dir, 'README.md'))) problems.push(`index: ${s.outputDir}/README.md missing (run emit-adlc-index.js)`);
  for (const o of s.outputs || []) {
    const m = String(o).match(/^(adlc\/[^\s,*<(]+)/);
    if (!m || /report\.(json|md)|latest-proposal/.test(m[1]) || /\(only when/.test(o)) continue; // runtime-only or conditional outputs
    if (!fs.existsSync(path.join(P.ROOT, m[1]))) problems.push(`spec: ${d.name} declares ${m[1]}, which does not exist`);
  }
}

// 7. Guardrails: no secrets anywhere in the repository (patterns in guardrails/guardrails.json)
const G = JSON.parse(fs.readFileSync(path.join(P.ROOT, 'guardrails', 'guardrails.json'), 'utf8'));
const pats = G.secretPatterns.map((s) => ({ name: s.name, re: new RegExp(s.regex.replace(/^\(\?i\)/, ''), s.regex.startsWith('(?i)') ? 'i' : '') }));
const skip = new RegExp(G.secretScanSkip.map((s) => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')).join('|'));
const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: P.ROOT }).toString().split('\0').filter(Boolean).filter((f) => !skip.test(f) && !/\.(pptx|png|jpe?g|zip)$/i.test(f));
for (const f of tracked) {
  const abs = path.join(P.ROOT, f); if (!fs.existsSync(abs)) continue;
  const t = fs.readFileSync(abs, 'utf8');
  // a line may opt out with a reviewed marker, e.g. throwaway test fixtures: `guardrails:allow test-fixture`
  const lines = t.split('\n').filter((l) => !/guardrails:allow/.test(l)).join('\n');
  for (const p of pats) if (p.re.test(lines)) problems.push(`secret: ${f} matches "${p.name}"`);
}
// 7b. Private identifiers (org username, instance, org ID, people's names) never reach the public repository.
// The values live in a git-ignored file, so the check itself publishes nothing; one literal per line.
const PRIVATE = path.join(P.ROOT, '.secrets', 'private-identifiers.txt');
if (fs.existsSync(PRIVATE)) {
  const ids = fs.readFileSync(PRIVATE, 'utf8').split(/\r?\n/).map((s) => s.trim()).filter((s) => s && !s.startsWith('#')).map((s) => s.toLowerCase());
  const all = execFileSync('git', ['ls-files', '-z'], { cwd: P.ROOT }).toString().split('\0').filter((f) => f && !/\.(pptx|pdf|png|jpe?g|zip)$/i.test(f));
  for (const f of all) {
    const abs = path.join(P.ROOT, f); if (!fs.existsSync(abs)) continue;
    const t = fs.readFileSync(abs, 'utf8').toLowerCase();
    if (ids.some((id) => t.includes(id))) problems.push(`private: ${f} contains a value listed in .secrets/private-identifiers.txt`);
  }
}
// 8. Knowledge base and guardrails exist, and every agent follows at least one KB page that exists
for (const f of ['kb/README.md', 'guardrails/README.md', 'guardrails/guardrails.json']) if (!fs.existsSync(path.join(P.ROOT, f))) problems.push(`standards: ${f} missing`);
for (const d of fs.readdirSync(P.AGENTS, { withFileTypes: true }).filter((x) => x.isDirectory() && fs.existsSync(path.join(P.AGENTS, x.name, 'agent.json')))) {
  const s = JSON.parse(fs.readFileSync(path.join(P.AGENTS, d.name, 'agent.json'), 'utf8'));
  if (!(s.kb || []).length) problems.push(`kb: ${d.name} lists no knowledge-base pages`);
  for (const k of s.kb || []) if (!fs.existsSync(path.join(P.ROOT, k))) problems.push(`kb: ${d.name} refers to missing ${k}`);
}

if (problems.length) { console.error(`conventions: ${problems.length} problem(s)\n${problems.map((p) => `  - ${p}`).join('\n')}`); process.exit(1); }
console.log(`conventions: OK (${walk(P.SRC, (p) => /\.(js|mjs)$/.test(p)).length} source files, ${P.sqlFiles().length} migrations, ${walk(P.ADLC, (p) => p.endsWith('.md')).length} documents checked)`);
