// The ADLC index: adlc/README.md plus a README in every agent's output folder, generated from the agent
// specs (src/agents/<agent>/agent.json) and src/agents/workflow.json. CI regenerates it and fails if it drifted.
//
//   node src/generators/emit-adlc-index.js
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const P = require('../paths');

// Only files tracked in git count, so the index is the same on every machine (local, ignored files excluded).
const tracked = execFileSync('git', ['ls-files', '-z', '--', 'adlc'], { cwd: P.ROOT }).toString().split('\0').filter(Boolean).map((f) => path.join(P.ROOT, f));

const wf = JSON.parse(fs.readFileSync(path.join(P.AGENTS, 'workflow.json'), 'utf8'));
const specs = Object.fromEntries(fs.readdirSync(P.AGENTS, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(P.AGENTS, d.name, 'agent.json')))
  .map((d) => [d.name, JSON.parse(fs.readFileSync(path.join(P.AGENTS, d.name, 'agent.json'), 'utf8'))]));
const row = (cells) => `| ${cells.map((c) => String(c ?? '').replace(/\|/g, '\\|')).join(' | ')} |`;
const list = (xs) => (xs || []).map((x) => `- ${String(x).replace(/^(adlc\/[^ ,]+|src\/[^ ,]+)/, '`$1`')}`).join('\n');
const stamp = 'Generated by `src/generators/emit-adlc-index.js` from the agent specs. Do not edit; edit `src/agents/<agent>/agent.json`.';

// What is in a folder: entries one level down, with file counts for large subfolders.
function contents(dir) {
  const inDir = tracked.filter((f) => f.startsWith(dir + path.sep));
  const top = new Map();
  for (const f of inDir) {
    const [first, ...rest] = path.relative(dir, f).split(path.sep);
    if (first === 'README.md') continue;
    top.set(first, rest.length ? (top.get(first) || 0) + 1 : null);
  }
  return [...top.entries()].sort(([a], [b]) => a.localeCompare(b))
    .map(([n, c]) => (c == null ? `- \`${n}\`` : `- \`${n}/\` (${c} files)`)).join('\n') || '_empty_';
}

// One README per agent output folder
for (const [id, s] of Object.entries(specs)) {
  if (!s.outputDir) continue;
  const dir = path.join(P.ROOT, s.outputDir);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'README.md'), [
    `# ${s.name}`, '', `Owner: ${s.name} · phase: ${s.phase} · ${s.kind === 'llm' ? 'language model proposals, reviewed before merge' : 'deterministic'}`, '', stamp, '',
    s.role, '',
    '## Inputs', '', list(s.inputs), '',
    '## Runs', '', list(s.implementation || [s.prompt].filter(Boolean)), '',
    '## Outputs', '', list(s.outputs), '',
    '## Done when', '', s.done_when || '', '',
    '## Reviewer checks at the gate', '', list(s.reviewer_checks), '',
    '## In this folder', '', contents(dir), '',
    `Spec: \`src/agents/${id}/agent.json\``, '',
  ].join('\n'));
}

// Go-live has no agent; it is the pipeline plus the infrastructure code
fs.writeFileSync(path.join(P.GO_LIVE, 'README.md'), [
  '# Go-live', '', 'Owner: CI/CD pipeline · phase: go-live', '', stamp, '',
  'Approved changes are pushed to `main`; the pipeline re-runs every check and deploys. Infrastructure is code in `infra/`.', '',
  '## Pipeline', '', '- `.github/workflows/crm-genie.yml`: tests, blueprint, SQL and document regeneration (must match git), conventions check, parity, app smoke test, deploy, health check', '',
  '## In this folder', '', contents(P.GO_LIVE), '',
].join('\n'));

// The top-level index
const phases = wf.phases.map((ph, i) => {
  const agents = ph.agents.map((a) => specs[a]).filter(Boolean);
  const extra = ph.on_failure && specs[ph.on_failure] ? [specs[ph.on_failure]] : [];
  return [...agents, ...extra].map((s) => row([`${i + 1} ${ph.title}`, s.name, `[\`${s.outputDir}/\`](${s.outputDir.replace(/^adlc\//, '')}/README.md)`, (s.outputs || []).length]))
    .concat(ph.pipeline ? [row([`${i + 1} ${ph.title}`, 'CI/CD pipeline', '[`adlc/6-go-live/`](6-go-live/README.md)', '—'])] : []);
}).flat();
fs.writeFileSync(path.join(P.ADLC, 'README.md'), [
  '# ADLC: what each agent produces', '', stamp, '',
  'Every output of the migration lives here, in the folder of the agent that produces it, and is reviewed at that phase’s gate. The code that produces or runs these outputs is in `src/`.', '',
  row(['Phase', 'Agent', 'Outputs', 'Declared outputs']), row(['---', '---', '---', '---']), ...phases, '',
  '## Layout', '', '```',
  'adlc/',
  '  1-discover/extraction/      metadata, schema, logic, data, inventory (gap register)',
  '  2-design/modelling/         blueprint, design (HLD, LLD, ADRs, diagrams), vendor packages',
  '  3-build/schema|logic|security/   numbered SQL migrations, translations, credentials checklist',
  '  4-migrate/data-load/        history archive plan, work in progress at go-live',
  '  5-validate/verification|repair/  parity cases and report, platform behaviour, repair proposals',
  '  6-go-live/                  infrastructure as code; pipeline in .github/workflows',
  'src/',
  '  paths.js                    the one place that knows this layout',
  '  generators/                 extraction, blueprint, SQL, documents, index, conventions check',
  '  agents/                     agent specs, entry points, runner with review gates',
  '  app/  verification/  console/  salesforce-seed/',
  '```', '',
  '## Standards', '',
  '- Design documents follow arc42, with C4 context and container views and ADRs for each design decision: `2-design/modelling/design/`.',
  '- Every generated file names its owner agent and generator; the LLD traceability matrix links each Salesforce element to its decision, artifact and test.',
  '- Conventions and patterns: `src/CONVENTIONS.md`; enforced by `src/generators/check-conventions.js` in CI.', '',
].join('\n'));
console.log(`adlc index: README + ${Object.values(specs).filter((s) => s.outputDir).length} agent READMEs + go-live`);
