// The evals suite: test assets for testing teams, generated from the blueprint, the parity cases and the agent
// specs, so they stay in step with the system. Deterministic (no run dates); CI regenerates and diffs.
//
//   node src/generators/emit-evals.js
//
//   evals/functional/test-cases.md|csv        every parity case as a manual + automated test case
//   evals/data-reconciliation/checks.md|csv   one check per object (row counts) and per calculated field
//   evals/security/access-matrix.csv          expected object access per role (from Salesforce)
//   evals/uat/scenarios.md                    business scenarios in Given/When/Then
//   evals/agent-evals/*.json                  golden sets and seeded faults for the Logic and Repair agents
//   evals/traceability.csv, evals/coverage.md  Salesforce element -> test cases; what is not yet covered
const fs = require('fs');
const path = require('path');
const P = require('../paths');

const EV = path.join(P.ROOT, 'evals');
const bp = JSON.parse(fs.readFileSync(P.BLUEPRINT, 'utf8'));
const { cases } = JSON.parse(fs.readFileSync(P.PARITY_CASES, 'utf8'));
const manifest = JSON.parse(fs.readFileSync(P.DB_MANIFEST, 'utf8'));
const FAMILY = manifest.family;
const ALL = [...FAMILY, ...manifest.referenceTables];
const ent = Object.fromEntries(bp.entities.map((e) => [e.id, e]));
const label = (id) => ent[id]?.label || id;
const fieldLabel = (eid, src) => ent[eid]?.fields.find((f) => f.source === src)?.label || src;
const cons = Object.fromEntries(bp.constraints.map((c) => [c.id, c]));
const stamp = (what) => `Owner: Verification agent · generated by \`src/generators/emit-evals.js\` from ${what}. Do not edit; edit the source and re-run.`;
const csv = (rows) => rows.map((r) => r.map((c) => { const s = String(c ?? ''); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; }).join(',')).join('\n') + '\n';
const md = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map((c) => String(c ?? '').replace(/\|/g, '\\|').replace(/\n/g, '<br>')).join(' | ')} |`)].join('\n');
const write = (rel, text) => { const f = path.join(EV, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); };

// ---------------------------------------------------------------- functional test cases from parity cases
const val = (v) => (v === '@today' ? 'today' : typeof v === 'string' && v.startsWith('@today+') ? `today + ${v.slice(7)}` : typeof v === 'string' && v.startsWith('@') ? `the ${v.slice(1)} record` : JSON.stringify(v));
const vals = (eid, o) => Object.entries(o || {}).map(([k, v]) => `${fieldLabel(eid, k)} = ${val(v)}`).join(', ');
const roleText = (r) => (r ? `As ${r.replace(/^profile:/, 'profile ').replace(/^permissionSet:/, 'permission set ')}, ` : '');
function render(c) {
  const alias = {};
  const steps = [], expects = [];
  for (const s of c.steps || []) {
    const who = roleText(s.role);
    if (s.insert) { if (s.as) alias[s.as] = s.insert; steps.push(`${who}create ${/^[AEIOU]/i.test(label(s.insert)) ? 'an' : 'a'} ${label(s.insert)}${s.values ? ` with ${vals(s.insert, s.values)}` : ''}${s.as ? ` (call it ${s.as})` : ''}`); }
    else if (s.update) steps.push(`${who}change ${s.update}: ${vals(alias[s.update], s.values)}`);
    else if (s.delete) steps.push(`${who}delete ${s.delete}`);
    else if (s.read) steps.push(`${who}open ${s.read}`);
    else if (s.count) steps.push(`${who}count ${label(s.count)} records where ${vals(s.count, s.where)}`);
    const n = steps.length;
    if (s.expectError) {
      const c2 = cons[s.expectError];
      expects.push(`Step ${n}: rejected${c2 ? ` with "${c2.message}"` : s.expectError.startsWith('system:') ? ` (${s.expectError.slice(7).replace(/_/g, ' ')})` : ` by ${s.expectError}`}`);
    } else if (s.expect !== undefined) {
      expects.push(`Step ${n}: ${typeof s.expect === 'object' ? vals(alias[s.read] || s.count, s.expect) : `result is ${s.expect}`}`);
    } else if (s.insert || s.update || s.delete) expects.push(`Step ${n}: succeeds`);
  }
  return { steps, expects };
}
const area = (id) => ({ apex: 'Business logic (Apex)', rule: 'Validation rules', platform: 'Platform behaviour', security: 'Security' }[id.split('.')[0]] || 'Other');
const title = (id) => id.split('.').slice(1).join(' ').replace(/_/g, ' ').replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase());
const TC = cases.map((c, i) => {
  const r = render(c);
  return { tc: `TC-${String(i + 1).padStart(3, '0')}`, id: c.id, area: area(c.id), title: title(c.id), origin: c.origin, steps: r.steps, expects: r.expects, status: c.pending ? `pending: ${c.pending}` : 'automated', priority: c.id.startsWith('security') || c.id.startsWith('rule') ? 'P1' : 'P2' };
});
write('functional/test-cases.csv', csv([['Test case', 'Parity case', 'Area', 'Title', 'Priority', 'Comes from', 'Steps', 'Expected', 'Automation'], ...TC.map((t) => [t.tc, t.id, t.area, t.title, t.priority, t.origin, t.steps.map((s, i) => `${i + 1}. ${s}`).join('\n'), t.expects.join('\n'), t.status])]));
write('functional/test-cases.md', [
  '# Functional test cases', '', stamp('`adlc/5-validate/verification/cases.json`'), '',
  'Each case is automated by the Verification agent (`src/verification/run.js`) and can also be run by hand in the app. Spreadsheet version: [test-cases.csv](test-cases.csv).', '',
  md(['Test case', 'Area', 'Title', 'Priority', 'Automation'], TC.map((t) => [t.tc, t.area, t.title, t.priority, t.status])), '',
  ...TC.flatMap((t) => [`## ${t.tc} ${t.title}`, '', `Area: ${t.area} · priority ${t.priority} · parity case \`${t.id}\` · comes from \`${t.origin}\` · ${t.status}`, '',
    ...(t.steps.length ? ['**Steps**', '', ...t.steps.map((s, i) => `${i + 1}. ${s}`), '', '**Expected**', '', ...t.expects.map((e) => `- ${e}`), ''] : ['_Not yet automatable; see status._', '']),
  ]),
].join('\n'));

// ---------------------------------------------------------------- data reconciliation
const recon = [
  ...ALL.map((e) => ['DR-COUNT', `${label(e)}: row count`, `${ent[e]?.rowCount ?? 0} rows in the target, as exported from Salesforce`, 'Data load agent (load report)']),
  ...bp.derivations.filter((d) => FAMILY.includes(d.entity) && d.kind !== 'platform').map((d) => ['DR-VALUE', `${d.field}: ${d.kind}`, `every row equals the value Salesforce stored (${ent[d.entity]?.rowCount ?? 0} rows)`, 'Verification agent (derived values)']),
  ...ALL.map((e) => ['DR-IDS', `${label(e)}: Salesforce IDs`, 'every record keeps its [REDACTED_GENERIC_API_KEY_1] Salesforce ID; no duplicates', 'Data load agent (primary key)']),
].map((r, i) => [`${r[0]}-${String(i + 1).padStart(3, '0')}`, ...r.slice(1)]);
write('data-reconciliation/checks.csv', csv([['Check', 'What', 'Expected', 'Automated by'], ...recon]));
write('data-reconciliation/checks.md', ['# Data reconciliation checks', '', stamp('the blueprint and `adlc/3-build/manifest.json`'), '', md(['Check', 'What', 'Expected', 'Automated by'], recon), ''].join('\n'));

// ---------------------------------------------------------------- security access matrix
const roles = bp.security.filter((s) => FAMILY.some((o) => (s.objects?.[o] || []).length) && !/^(sfdc|X00e|force__)/.test(s.name));
const OPS = ['read', 'create', 'edit', 'delete'];
const matrix = roles.flatMap((r) => FAMILY.map((o) => [r.kind, r.name, label(o), ...OPS.map((op) => ((r.objects?.[o] || []).includes(op) ? 'allowed' : 'denied'))]));
write('security/access-matrix.csv', csv([['Kind', 'Role', 'Object', ...OPS.map((o) => `Can ${o}`)], ...matrix]));
write('security/README.md', ['# Security tests', '', stamp('the blueprint (profiles, permission sets, sharing)'), '',
  'Each row of [access-matrix.csv](access-matrix.csv) is a test: sign in as the role and confirm each operation is allowed or denied exactly as in Salesforce. Automated cases: the `security.*` cases in [functional/test-cases.md](../functional/test-cases.md).', '',
  md(['Role', 'Object', ...OPS], roles.flatMap((r) => FAMILY.map((o) => [`${r.kind === 'profile' ? 'Profile' : 'Permission set'}: ${r.name}`, label(o), ...OPS.map((op) => ((r.objects?.[o] || []).includes(op) ? '✓' : '—'))]))), ''].join('\n'));

// ---------------------------------------------------------------- UAT scenarios
const st = ent['Subscription__c']?.fields.find((f) => f.source === 'Status__c');
const rules = bp.constraints.filter((c) => FAMILY.includes(c.entity));
const uat = [
  { t: 'Create a subscription for a customer', g: 'an account exists', w: 'a user creates a subscription with start and end dates', th: `it is saved with status ${st?.default || 'Draft'}, a subscription number, and the term and health score filled in` },
  { t: 'Activate a subscription', g: 'a draft subscription with a monthly value above zero', w: 'the user sets the status to Active', th: 'it is saved and its annual value shows twelve times the monthly value' },
  ...rules.map((c) => ({ t: `Rule: ${c.name.replace(/_/g, ' ')}`, g: `a ${label(c.entity).toLowerCase()} that breaks the rule (${c.source.replace(/\s+/g, ' ')})`, w: 'the user saves it', th: `it is rejected with "${c.message}"` })),
  { t: 'Add lines and see totals', g: 'an active subscription', w: 'the user adds two lines with quantity and unit price', th: 'the line count and total line value on the subscription update immediately' },
  { t: 'Delete an account', g: 'an account with a subscription and lines', w: 'the account is deleted', th: 'its subscriptions and lines are deleted too' },
  { t: 'Read-only access', g: 'a user with a read-only profile', w: 'they open a subscription and try to change it', th: 'they can see it but the change is refused' },
];
write('uat/scenarios.md', ['# User acceptance scenarios', '', stamp('the blueprint (statuses, rules, relationships, access)'), '',
  'Business-readable scenarios for user acceptance testing. Each has a matching automated case where one exists; testers sign off each scenario in the app.', '',
  ...uat.flatMap((u, i) => [`## UAT-${String(i + 1).padStart(2, '0')} ${u.t}`, '', `- **Given** ${u.g}`, `- **When** ${u.w}`, `- **Then** ${u.th}`, '', 'Result: ☐ pass ☐ fail · tester: ______ · date: ______', '']),
].join('\n'));

// ---------------------------------------------------------------- agent evals (Logic and Repair agents)
const tdir = P.TRANSLATIONS;
const index = fs.existsSync(path.join(tdir, 'index.json')) ? JSON.parse(fs.readFileSync(path.join(tdir, 'index.json'), 'utf8')) : [];
const methods = bp.services.flatMap((s) => (s.methods || []).map((m) => ({ cls: s.source.name, method: m, id: `${s.id}#${m}` })));
const logicEval = {
  agent: 'logic', purpose: 'Golden set for Apex translation: each method, the cases its translation must pass, and its review status.',
  passCriteria: ['every listed parity case passes', 'reviewer rubric score >= 4 of 5 on each criterion', 'no grant widened, no dynamic SQL from input'],
  items: methods.map((m) => {
    const done = index.find((t) => (t.implements || []).includes(m.id));
    return { method: `${m.cls}.${m.method}`, translation: done ? P.rel(path.join(tdir, done.file)) : null, reviewed: done ? !!done.reviewed : false,
      mustPass: cases.filter((c) => c.id.toLowerCase().includes(m.method.toLowerCase().replace(/^handle/, '')) || (c.origin || '').toLowerCase().includes(m.method.toLowerCase())).map((c) => c.id),
      status: done ? 'translated' : 'pending' };
  }),
};
const repairEval = {
  agent: 'repair', purpose: 'Seeded faults: break the generator in a known way and check the Repair agent finds the root cause and proposes a fix to the generator only.',
  passCriteria: ['diagnosis names the seeded root cause', 'patch touches src/generators/ only', 'all parity cases pass after the patch', 'no grant widened'],
  items: [
    { id: 'RF-01', seed: 'drop the column-level UPDATE grant for one permission set in the security emitter', expectFailingCase: 'security.permsetEditsAllowedFields', expectRootCause: 'missing column grant' },
    { id: 'RF-02', seed: 'treat blank as blank instead of zero in generated formula columns', expectFailingCase: 'derived values: Subscription__c.Annual_Value__c', expectRootCause: 'blank-as-zero not applied' },
    { id: 'RF-03', seed: 'compile a PRIORVALUE rule as a CHECK constraint', expectFailingCase: 'rule.No_Reactivation_After_Cancel.toSuspended', expectRootCause: 'rule needs the previous row; must be a guard trigger' },
    { id: 'RF-04', seed: 'remove the roll-up recompute after load', expectFailingCase: 'derived values: Subscription__c.Total_Line_Value__c', expectRootCause: 'roll-ups not recomputed in load mode' },
  ],
};
write('agent-evals/logic-translation.json', JSON.stringify(logicEval, null, 2) + '\n');
write('agent-evals/repair-seeded-faults.json', JSON.stringify(repairEval, null, 2) + '\n');
write('agent-evals/README.md', ['# Agent evals', '', stamp('the blueprint, translations and parity cases'), '',
  'How we measure the output of the Logic and Repair agents (the two that use a language model), not only the system they build.', '',
  md(['Eval', 'Agent', 'Items', 'Pass criteria'], [
    ['[logic-translation.json](logic-translation.json)', 'Logic', logicEval.items.length, logicEval.passCriteria.join('; ')],
    ['[repair-seeded-faults.json](repair-seeded-faults.json)', 'Repair', repairEval.items.length, repairEval.passCriteria.join('; ')],
  ]), '',
  '## Reviewer rubric (score 1 to 5)', '',
  md(['Criterion', '5 means'], [['Correctness', 'behaviour matches the Apex, including edge cases and nulls'], ['Safety', 'no widened access, parameterised SQL, follows kb/secure-coding.md'], ['Fit', 'uses the patterns in kb/salesforce-translation-playbook.md and kb/postgres-standards.md'], ['Clarity', 'readable, named after the source, provenance header present'], ['Testability', 'the listed parity cases cover it; gaps are named']]), ''].join('\n'));

// ---------------------------------------------------------------- traceability and coverage
const elements = [
  ...bp.constraints.filter((c) => FAMILY.includes(c.entity)).map((c) => ['validation rule', c.id, c.name]),
  ...bp.derivations.filter((d) => FAMILY.includes(d.entity) && d.kind !== 'platform').map((d) => [d.kind, d.id, d.field.split('.')[1]]),
  ...methods.map((m) => ['apex method', m.id, m.method]),
  ...roles.map((r) => [r.kind, r.id, 'security']),
];
const tcFor = (needle) => TC.filter((t) => t.id.toLowerCase().includes(needle.toLowerCase().replace(/__c$/, '').replace(/^handle/, ''))).map((t) => t.tc);
const trace = elements.map(([k, id, n]) => {
  const tcs = tcFor(n), dr = recon.filter((r) => r[1].startsWith(id)).map((r) => r[0]);
  return [k, id, [...tcs, ...dr].join(' '), tcs.length || dr.length ? 'covered' : 'gap'];
});
write('traceability.csv', csv([['Element kind', 'Blueprint ID', 'Tests', 'Coverage'], ...trace]));
const gaps = trace.filter((t) => t[3] === 'gap');
write('coverage.md', ['# Test coverage', '', stamp('the blueprint and the evals above'), '',
  md(['Measure', 'Value'], [
    ['Functional test cases', `${TC.length} (${TC.filter((t) => t.status === 'automated').length} automated, ${TC.filter((t) => t.status !== 'automated').length} pending)`],
    ['Data reconciliation checks', recon.length], ['Security matrix rows', matrix.length], ['UAT scenarios', uat.length],
    ['Elements in scope', elements.length], ['Elements with at least one test', `${elements.length - gaps.length} of ${elements.length}`],
  ]), '',
  '## Gaps (elements with no test yet)', '', gaps.length ? md(['Kind', 'Blueprint ID'], gaps.map((g) => [g[0], g[1]])) : '_None._', '',
].join('\n'));
console.log(`evals: ${TC.length} test cases, ${recon.length} reconciliation checks, ${matrix.length} security rows, ${uat.length} UAT scenarios, ${elements.length - gaps.length}/${elements.length} elements covered -> evals/`);
