// Reports, dashboards and email templates live in folders, and a * wildcard returns none of them.
// Each folder is listed first, then its contents.
const FOLDERED = [
  { type: 'Report', folderType: 'ReportFolder', unfiled: 'unfiled$public' },
  { type: 'Dashboard', folderType: 'DashboardFolder' },
  { type: 'EmailTemplate', folderType: 'EmailFolder', unfiled: 'unfiled$public' },
  { type: 'Document', folderType: 'DocumentFolder' },
];

const asArray = (x) => (x == null ? [] : Array.isArray(x) ? x : [x]);

async function listFoldered(conn) {
  const out = {};
  for (const { type, folderType, unfiled } of FOLDERED) {
    try {
      const folders = asArray(await conn.metadata.list([{ type: folderType }], API)).map((f) => f.fullName);
      if (unfiled) folders.push(unfiled);
      const members = new Set(folders.filter((f) => f !== unfiled));
      for (let i = 0; i < folders.length; i += 3) { // list() takes at most 3 queries per call
        const queries = folders.slice(i, i + 3).map((folder) => ({ type, folder }));
        for (const m of asArray(await conn.metadata.list(queries, API))) members.add(m.fullName);
      }
      out[type] = [...members].sort();
    } catch (e) {
      console.warn(`  ${type}: folder listing unavailable (${e.message})`);
      out[type] = [];
    }
  }
  return out;
}

// Wildcards don't cover standard objects, so they are listed explicitly. Types this org does not
// have (for example Territory2 when territories are off) are dropped rather than failing the retrieve.
async function writeManifest(conn, objectNames) {
  const available = new Set();
  const childOf = {}; // child type -> parent type; children come with their parent's retrieve
  try {
    const d = await conn.metadata.describe(API);
    for (const t of d.metadataObjects) {
      available.add(t.xmlName);
      for (const c of asArray(t.childXmlNames)) { available.add(c); childOf[c] = t.xmlName; }
    }
  } catch (e) {
    console.warn(`  describeMetadata unavailable, keeping the full type list (${e.message})`);
  }
  const wildcard = available.size ? WILDCARD.filter((t) => available.has(t)) : WILDCARD;
  const foldered = await listFoldered(conn);
  const block = (name, members) => `    <types>\n${members.map((m) => `        <members>${m}</members>`).join('\n')}\n        <name>${name}</name>\n    </types>`;
  const types = [
    block('CustomObject', [...objectNames, '*']),
    ...wildcard.map((t) => block(t, ['*'])),
    ...Object.entries(foldered).filter(([, m]) => m.length).map(([t, m]) => block(t, m)),
  ];
  const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<Package xmlns="http://soap.sforce.com/2006/04/metadata">\n${types.join('\n')}\n    <version>${API}</version>\n</Package>\n`;
  fs.writeFileSync(P.RETRIEVE_MANIFEST, xml);
  writeJson(path.join(OUT, 'inventory', 'manifest-coverage.json'), {
    requested: WILDCARD.length,
    retrieved: wildcard,
    notInThisOrg: WILDCARD.filter((t) => !wildcard.includes(t)),
    // items only; folder names (no slash) are members too, so the folders themselves are retrieved
    foldered: Object.fromEntries(Object.entries(foldered).map(([t, m]) => [t, m.filter((x) => x.includes('/')).length])),
    availableInOrg: [...available].sort(),
    childOf,
  });
  const counts = Object.entries(foldered).map(([t, m]) => `${m.filter((x) => x.includes('/')).length} ${t}`).join(', ');
  console.log(`${P.rel(P.RETRIEVE_MANIFEST)}: ${objectNames.length} objects + ${wildcard.length} wildcard types + ${counts}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
